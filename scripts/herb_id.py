def herb_id_notes(ingredients_text: str) -> list[dict]:
    """从原料串里找出易混药材，返回辨识要点列表（保序去重）。

    返回空列表表示这批原料没有需要特别提示的易混药材。

    匹配顺序按关键词长度降序：长名优先。具体名（川贝母）包含泛称
    （贝母）时，具体名命中后泛称不再重复提示；泛称单独出现（裸名
    「贝母」）时仍正常命中。
    """
    text = ingredients_text or ""
    notes: list[dict] = []
    matched_variants: set[str] = set()
    # 长度降序：川贝母/浙贝母 先于 贝母 匹配
    for keyword in sorted(CONFUSED_HERBS, key=len, reverse=True):
        entry = CONFUSED_HERBS[keyword]
        if keyword not in text:
            continue
        primary_variant = entry["variants"][0]
        if primary_variant in matched_variants:
            continue
        # 泛称条目（贝母）若具体名（川贝母/浙贝母）已命中则跳过
        if len(keyword) == 2 and any(
                v in text for v in entry["variants"]):
            continue
        matched_variants.add(primary_variant)
        notes.append({
            "herb": keyword,
            "variants": list(entry["variants"]),
            "note": entry["note"],
        })
    return notes
